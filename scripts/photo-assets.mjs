/**
 * Generates responsive hero photo files from the master in assets/photos (masters are NOT shipped).
 *   node scripts/photo-assets.mjs        (also: npm run photos)
 *
 * Input : assets/photos/hero-golden-hour.png (owner photo, any size ≥ 1200px wide)
 * Output: public/images/brand/hero-golden-hour-{w}.{avif,webp}   4:3 crop, several widths
 *         public/images/brand/hero-golden-hour-blur.webp     tiny pre-blurred full frame (hero colour wash, ~3 KB)
 *         src/data/heroPhoto.ts (generated: widths + intrinsic size → no layout shift)
 *
 * Crop: 4:3 window positioned by FOCUS_X (0 = left edge, 1 = right edge) so the cup, the burger box and
 * Faisal Mosque all stay in frame. Change FOCUS_X if the photo is replaced.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(root, 'assets/photos/hero-golden-hour.png')
const OUT_DIR = join(root, 'public/images/brand')
const NAME = 'hero-golden-hour'
const RATIO = 4 / 3
const FOCUS_X = 0.6
const WIDTHS = [480, 720, 960, 1280]

const meta = await sharp(SRC).metadata()
const cropH = meta.height
const cropW = Math.min(meta.width, Math.round(cropH * RATIO))
const left = Math.round((meta.width - cropW) * FOCUS_X)
const widths = [...WIDTHS.filter((w) => w < cropW), cropW]

for (const w of widths) {
  const base = sharp(SRC).extract({ left, top: 0, width: cropW, height: cropH }).resize({ width: w })
  await base.clone().avif({ quality: 52, effort: 6 }).toFile(join(OUT_DIR, `${NAME}-${w}.avif`))
  await base.clone().webp({ quality: 74, effort: 6 }).toFile(join(OUT_DIR, `${NAME}-${w}.webp`))
  console.log(`✓ ${NAME}-${w}.{avif,webp}`)
}

// Ambient wash: whole frame, tiny + pre-blurred (upscaled by CSS; far cheaper than a live CSS blur on phones).
await sharp(SRC).resize({ width: 160 }).blur(6).webp({ quality: 60 }).toFile(join(OUT_DIR, `${NAME}-blur.webp`))
console.log(`✓ ${NAME}-blur.webp`)

writeFileSync(
  join(root, 'src/data/heroPhoto.ts'),
  `// GENERATED by scripts/photo-assets.mjs (npm run photos). Do not edit by hand.
export const HERO_PHOTO = {
  base: '/images/brand/${NAME}',
  widths: ${JSON.stringify(widths)},
  blur: '/images/brand/${NAME}-blur.webp',
  width: ${cropW},
  height: ${cropH},
} as const
`,
)
console.log(`✓ src/data/heroPhoto.ts (${cropW}×${cropH}, crop left ${left}px)`)
