import { site } from '@/config/site'
import { cn } from '@/lib/utils'
import { BrandImage } from './BrandImage'
import { LogoStamp } from './LogoStamp'

export type LogoVariant = 'full' | 'icon' | 'wordmark' | 'horizontal' | 'stamp'

interface LogoProps {
  variant?: LogoVariant
  /** Height in px (stamp: diameter). */
  size?: number
  /**
   * dark  = on oat/cheese backgrounds (logo as-is).
   * light = on espresso/chili backgrounds → logo sits on an oat badge (never recoloured).
   */
  tone?: 'dark' | 'light'
  /** Empty string = decorative. */
  alt?: string
  priority?: boolean
  className?: string
}

/** The one logo component. Uses the real logo artwork (public/brand, generated by scripts/brand-assets.mjs). */
export function Logo({ variant = 'full', size = 64, tone = 'dark', alt = site.brandName, priority, className }: LogoProps) {
  if (variant === 'stamp') return <LogoStamp size={size} className={className} />

  const art =
    variant === 'horizontal' ? (
      <span className="inline-flex items-center gap-2" role={alt ? 'img' : undefined} aria-label={alt || undefined}>
        <BrandImage kind="icon" height={size} alt="" priority={priority} />
        <BrandImage kind="wordmark" height={Math.round(size * 0.62)} alt="" priority={priority} />
      </span>
    ) : (
      <BrandImage kind={variant} height={size} alt={alt} priority={priority} />
    )

  if (tone === 'dark') return <span className={cn('inline-flex', className)}>{art}</span>

  // Padding derived from the logo size (percent padding would resolve against the PARENT width).
  const pad = Math.round(size * 0.16)
  const badgeShape = variant === 'icon' ? 'rounded-full' : variant === 'full' ? 'rounded-blob' : 'rounded-full'
  const padding = variant === 'icon' || variant === 'full' ? pad : `${Math.round(size * 0.2)}px ${Math.round(size * 0.4)}px`
  return (
    <span className={cn('sticker inline-flex items-center justify-center bg-oat', badgeShape, className)} style={{ padding }}>
      {art}
    </span>
  )
}
